CREATE TABLE events (
    id VARCHAR(36) NOT NULL,
    user_id VARCHAR(36) NOT NULL,
    name VARCHAR(120) NOT NULL,
    note VARCHAR(2000) NULL,
    date DATE NOT NULL,
    category VARCHAR(40) NULL,
    mode VARCHAR(40) NULL,
    repeat_rule VARCHAR(20) NOT NULL,
    calendar_type VARCHAR(20) NULL,
    holiday_key VARCHAR(80) NULL,
    lunar_month INT NULL,
    lunar_day INT NULL,
    lunar_leap BOOLEAN NULL,
    icon VARCHAR(60) NULL,
    tint VARCHAR(60) NULL,
    pin BOOLEAN NOT NULL DEFAULT FALSE,
    reminder VARCHAR(60) NULL,
    reminder_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    reminder_days_before INT NOT NULL DEFAULT 3,
    reminder_time TIME NULL,
    sample BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY idx_events_user_date (user_id, date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
